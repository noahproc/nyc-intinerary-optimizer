// Offline catalog of NYC-area places. Hours are representative, not live:
// the Google Places provider replaces them when a key is configured.

const w = (open: number, close: number): TimeWindow[] => [{ start: open, end: close }];
/** Same hours every day. */
const daily = (open: number, close: number): WeeklyHours => Array.from({ length: 7 }, () => w(open, close));
/** Per-day hours, Sunday first; null = closed. */
const week = (...days: ([number, number] | null)[]): WeeklyHours => days.map((d) => (d ? w(d[0], d[1]) : []));

